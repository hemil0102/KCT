//  CommentaryWriter.swift
//  KCT
//
//  역할 : 틀린 문항에 대해 "왜 그것이 답인지" 한두 문장을 만든다
//  요점 : 나무라지 않고, 정답을 한 번 더 만나게 한다. 못 만들면 조용히 nil
//
//  ── 구성 ──────────────────────────────────────────────
//  Commentary (@Generable)   모델이 만들어 주는 해설 한 덩어리
//  └─ text                   두 문장 이내의 한국어
//
//  CommentaryWriter
//  └─ write(for:chosen:) async -> String?
//
//  ── 흐름 ──────────────────────────────────────────────
//  QuizSession.gradeCurrent() 가 오답을 만나면
//    → 창(feedback)을 먼저 띄우고
//    → write(for:chosen:) 호출
//    → 지침으로 문체를 세운 세션에 문제·정답·고른 답을 넘긴다
//    → 실패하면 nil — 창은 이미 떠 있으므로 아무 일도 일어나지 않는다
//
//  ── 연결 ──────────────────────────────────────────────
//  불러 쓰는 곳 : QuizSession.gradeCurrent()
//  기대는 것    : FoundationModels, QuizItem(문제와 정답)
//  건드리지 않는 것 : 화면 - 2단계에서는 만든 해설을 표시하지 않는다.
//                    ObsRecord 에만 남기고 20문항을 눈으로 검토한 뒤 3단계에서 띄운다
//

import Foundation
import FoundationModels

/// 오답 해설 한 덩어리. 모델이 이 구조체 모양으로 직접 만들어 준다.
///
/// 문장을 나눠 받지 않고 `text` 하나로 받는 이유 — 어머니가 창에서 읽는 것은
/// **이어지는 두 문장**입니다. 쪼개 받아 다시 붙이면 이음매가 어색해집니다.

@Generable
struct Commentary {
    @Guide(description: "정답을 기억에 남게 알려주는 한국어 설명. 세 문장 이내. 고르신 답이나 다른 보기를 언급하지 않는다.")
    let text: String
}

/// 틀린 문항의 해설을 쓰는 쪽. 온디바이스 모델을 쓴다.
///
/// ## 무엇을 지키게 하는가
///
/// | 지킬 것 | 왜 |
/// |---|---|
/// | 두 문장 이내 | 어머니는 창을 3~5초 봅니다. 세 문장이면 다 못 읽습니다 |
/// | 고른 답을 부정하지 않는다 | 8/28·8/31 기록에서 어머니는 **이미 자기가 틀린 걸 압니다.** 한 번 더 말할 이유가 없습니다 |
/// | 정답을 다시 말한다 | 창의 목적은 정답을 한 번 더 만나게 하는 것입니다 |
/// | 새로운 어려운 말을 꺼내지 않는다 | 「시조」를 설명하려고 「건국신화」를 꺼내면 모르는 말이 하나 늡니다 |
///
/// - Important: 실패해도 **던지지 않습니다.** ``MeaningGrader`` 는 판정을 못 하면
///   회차의 진행이 막히지만, 해설은 없어도 창이 뜹니다. 실패를 `nil` 로 돌려주면
///   ``ObsRecord/explanation`` 이 `null` 로 남고, 나중에 **몇 번 실패했는지 셀 수 있습니다.**
///
struct CommentaryWriter {
    /// 틀린 문항의 해설을 만든다. 못 만들면 `nil`.
    ///
    /// - Parameters:
    ///   - item: 방금 틀린 문항 (지문과 정답을 함께 넘긴다)
    ///   - chosen: 어머니가 고르거나 입력한 답
    /// - Returns: 두 문장 이내의 해설. 모델을 쓸 수 없거나 빈 문장이면 `nil`
    func write(for item: QuizItem) async -> String? {
        // 문체 규칙은 매번 같으므로 프롬프트가 아니라 지침에 둔다.
        // MeaningGrader 에서 배운 것 - 작은 온디바이스 모델은 규칙 문장보다
        // 예시를 훨씬 잘 따른다. 그래서 규칙마다 좋은 예와 나쁜 예를 붙인다.
        let instructions = """
        당신은 어르신에게 한국 귀화 시험에 필요한 한국 역사, 사회, 정치, 한국의 상식 및 제도 등을 알려주는 사람입니다.
        방금 문제를 놓친 분에게 정답을 기억에 남게 알려주는 짧은 글을 씁니다. 읽는 분은 한국어에 서투릅니다.

        \(guide(for: item.question.kind))

        [반드시 지킨다]
        1. 세 문장을 넘기지 않는다.
        2. 정답을 문장 안에 그대로 넣는다.
        3. 세 문장을 모두 정답을 설명하는 데에만 쓴다.
        4. 정답이 아닌 것은 아예 말하지 않는다.
        5. 마지막 문장까지 설명으로 채운다.
        6. 확실하지 않은 연도, 숫자, 글자 뜻은 넣지 않는다. 확실하지 않으면 그것이 무엇을 하는 것인지만 말한다.
        """

        
        let prompt = """
            문제: \(item.question.question)
            정답: \(item.question.answer)
            
            이 답을 기억에 남게 알려주는 세 문장 이내의 글을 쓰세요.
            """
        
        do {
            let session =
            LanguageModelSession(instructions: instructions)
            let response = try await session.respond(to: prompt, generating: Commentary.self)
            
            let text = response.content.text.trimmingCharacters(in: .whitespacesAndNewlines)
            return text.isEmpty ? nil : text
        } catch {
            // 이유를 버리면 「잠시만 같이 살펴봐요.」가 왜 남는지 알 수 없다.
            print("❌ 해설 실패:", error)
            return nil
        }
    }
    
    /// 이 종류의ㅁ 답을 어떻게 설명할지.
    ///
    /// 지침을 한 덩어리만 넣는 이유 — 열한 가지를 다 보내면 지침이 길어지고,
    /// 작은 온디바이스 모델은 **긴 지침의 앞부분을 놓칩니다.**
    /// 문항이 자기 종류를 알고 있으므로 그 한 줄만 골라 보냅니다.
    private func guide(for kind: AnswerKind) -> String {
        switch kind {
        case .meaning:
            """
            [목적] 단어의 뜻을 직관적으로 이해하여 정답이 머릿속에 자연스럽게 남도록 합니다.
            [지침] 어려운 용어를 초등학생 수준의 쉬운 말로 풀고, 왜 그 단어를 쓰는지 글자의 뜻을 나누어 설명하세요.
            [구조] "[정답]은 쉽게 말해서 ~라는 뜻입니다. 글자를 풀면 ~라는 의미가 됩니다."
            """
        case .list:
            """
            [목적] 여러 개의 정답 항목을 묶어서 한 번에 연상하도록 돕습니다.
            [지침] 한국어가 서툰 어르신을 위해 "전부 몇 개"인지 숫자를 가장 먼저 알려주고, 기억하기 쉬운 순서나 힌트로 묶어주세요.
            [구조] "알아두셔야 할 것은 전부 [개수]개입니다. 바로 [항목1], [항목2]입니다. [쉽게 연상하는 힌트]로 기억하면 쉽습니다."
            """
        case .number:
            """
            [목적] 숫자나 나이를 일상생활의 경험과 연결하여 오래 기억하게 합니다.
            [지침] 그 숫자가 어르신의 실생활에서 어떤 권리나 혜택(복지, 돈, 자격)과 이어지는지 짚어주세요.
            [구조] "[정답 숫자]는 [어떤 권리/혜택]을 받는 기준이 되는 숫자입니다. 이 시기가 되면 [구체적 혜택]을 받게 됩니다."
            """
        case .person:
            """
            [목적] 인물의 이름과 그 사람의 대표적인 업적을 하나로 묶어 각인시킵니다.
            [지침] 그 사람이 만든 가장 유명한 것 딱 하나만 말하고, 이름과 행동을 부드럽게 연결하세요. "꼭 외우세요" 같은 명령조는 쓰지 마세요.
            [구조] "[정답 인물]은 [가장 유명한 것]을 만든 고마운 사람입니다. [업적]을 세운 분으로 기억하시면 됩니다."
            """
        case .place:
            """
            [목적] 장소나 나라 이름을 들었을 때 그 장소의 이미지가 바로 떠오르게 합니다.
            [지침] 이름에 왜 그 글자가 들어갔는지 이름 풀이나 역사적 특징을 넣어 단어의 유래를 친절하게 설명하세요.
            [구조] "[정답]은 [역사적/지리적 특징]을 가진 곳입니다. 이름의 뜻을 풀면 [이름풀이]가 되어서 [정답]이라고 부릅니다."
            """
        case .day:
            """
            [목적] 기념일이나 명절의 이름을 문제의 내용과 직접 연결하여 기억하기 쉽게 해설합니다.
            [지침] 프롬프트(이 가이드라인)에 적혀 있는 예시 단어(떡국, 송편, 개천절, 추석 등)를 절대로 본문에 재사용하지 마세요. 오직 사용자가 입력한 '문제(Question) 텍스트' 안에 들어있는 설명만 사용하여 문장을 만드세요. 없는 지식을 새로 지어내거나 추측하여 계절, 날짜, 음식을 적으면 절대로 안 됩니다. "외우라"는 압박성 지시는 빼세요.
            [구조] "[정답]은 문제에 나온 설명처럼 [입력된 문제 지문 속의 핵심 설명 표현]을 하는 대표적인 날입니다. 그래서 [정답]이라고 부릅니다."
            """
        case .event:
            """
            [목적] 역사적 사건의 이름과 내용을 연결하여 머릿속에 연상되도록 합니다.
            [지침] "옛날에 일어난 큰일"이라고 쉽게 시작하고, 정답 단어에 들어간 숫자나 글자의 의미를 부드럽게 풀어주세요. 명령조의 문장은 제외합니다.
            [구조] "[정답]은 옛날에 일어난 큰 사건입니다. 이름에 [숫자/글자 뜻]이 들어간 이유는 당시에 [원인/날짜]가 있었기 때문입니다."
            """
        case .thing:
            """
            [목적] 한국 전통 물건이나 상징물의 이름을 용도와 엮어 이해하도록 돕습니다.
            [지침] 어르신들이 실생활에서 매일 보거나 쓰는 상황을 예로 들고, 왜 그런 이름이 붙었는지 눈에 그리듯 설명하세요. "기억해두세요" 같은 표현은 쓰지 않습니다.
            [구조] "[정답]은 주로 [언제/어떻게 쓰는] 물건입니다. 이 모양이나 이름에는 [의미]라는 뜻이 담겨 있습니다."
            """
        case .heritage:
            """
            [목적] 문화재나 오래된 책의 이름을 가치와 엮어 떠올릴 수 있게 합니다.
            [지침] 조상들이 만든 아주 소중한 보물이라고 친근하게 강조하고, 이름에 담긴 뜻이나 쓰임새를 부드럽게 이야기하듯 풀어주세요.
            [구조] "[정답]은 옛날 조상들이 만든 아주 소중한 보물입니다. [이름 뜻/쓰임새]라는 뜻을 담아서 [정답]이라고 부릅니다."
            """
        case .system:
            """
            [목적] 어려운 법이나 제도 이름을 복지 혜택과 연결하여 친숙하게 만듭니다.
            [지침] 어르신이 국가로부터 병원비나 생활비를 도움받는 상황을 예로 들어, 이름의 글자 뜻을 풀고 따뜻하게 설명하세요.
            [구조] "[정답]은 국민이 힘들 때 나라가 도와주는 참 좋은 제도입니다. 단어의 뜻 그대로 [이름풀이]를 해주는 시스템입니다."
            """
        case .procedure:
            """
            [목적] 행정 절차나 예절의 이름을 행동과 장소에 엮어 기억하게 합니다.
            [지침] "언제", "주민센터(동사무소)나 출입국사무소 중 어디로 가야 하는지" 행동을 알려주고, 그 행동의 이름이 정답이 된 이유를 풀어줍니다.
            [구조] "[정답]은 [어떤 상황]일 때, [어디]에 가서 신청하는 일입니다. [이 행동의 의미]를 뜻하는 말입니다."
            """
        }
    }
}
