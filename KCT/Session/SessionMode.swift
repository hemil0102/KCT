import Foundation

/// 이번 회차의 성격.
///
/// 도움 장치를 켤지 끌지를 이 한 값이 정합니다. 화면마다 "지금 연습인가?" 를
/// 따로 판단하면 어느 화면은 켜고 어느 화면은 끄는 사고가 생깁니다.
///
/// - Note: 앞으로 늘어날 자리입니다. 4단계(연습 모드 즉시 채점)에서는
///   "고르는 즉시 채점할까" 같은 판단도 여기에 붙게 됩니다.
enum SessionMode {
    /// 연습 모드 — 학습을 돕는 장치를 제공한다.
    case practice

    /// 실전 모드 — 실제 시험처럼 도움 없이 푼다.
    case exam

    /// 질문이 묻는 대상을 형광펜으로 강조할지.
    ///
    /// 연습에서만 켭니다. 실전에서는 스스로 읽고 무엇을 묻는지 판단해야
    /// 실제 시험과 같은 연습이 됩니다.
    var showsFocusHighlight: Bool {
        self == .practice
    }
}
